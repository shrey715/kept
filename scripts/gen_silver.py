# ruff: noqa: E501, SIM115  (one-off generator: long SQL templates)
"""Generate dbt/models/silver/<table>.sql from the release's schema.json (Track A).

    uv run python scripts/gen_silver.py ../maple_data/maple_collections_release/schema/schema.json

Silver = bronze with dictionary column names and types (K2) plus the rules in kept.data.clean
and kept.data.traps. Only the tables in EXTRAS get more than a typed select. The generated
files are committed, so nobody needs schema.json to run dbt.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

SILVER = Path(__file__).resolve().parents[1] / "dbt" / "models" / "silver"
HEADER = "{# Generated by scripts/gen_silver.py from the release schema.json. Edit the generator. #}\n"
LINEAGE = ("_source_file", "_extracted_at", "_loaded_at")


def sql_type(t: str) -> str | None:
    """Dictionary type -> DuckDB type (None = keep VARCHAR). Money stays DECIMAL, not float (K7)."""
    if m := re.fullmatch(r"decimal\((\d+),(\d+)\)", t):
        # widened: the dictionary's decimal(8,4) is too narrow for deposit_accounts.income_to_debt_service_ratio_est
        return f"DECIMAL({max(int(m[1]), 18)},{m[2]})"
    return {"int": "BIGINT", "boolean": "BOOLEAN", "date": "DATE", "timestamp": "TIMESTAMP"}.get(t)


# columns whose original text is kept next to the parsed value, as <name>_raw (additive)
RAW_TEXT = {
    # the Ask's roll rate is graded against a reference that parses only some of the formats
    "account_monthly_snapshot": ("month_end_date",),
}


def typed_columns(columns: list[dict], exclude: tuple[str, ...] = (), raw: tuple[str, ...] = ()) -> str:
    out = []
    for c in columns:
        if c["name"] in exclude:
            continue
        t = sql_type(c["type"])
        name = c["name"]
        if t == "DATE":  # date formats drift (account_monthly_snapshot.month_end_date arrives in three)
            out.append(f'        coalesce(try_cast("{name}" as DATE), kept_date("{name}")) as "{name}"')
        else:
            out.append(f'        try_cast("{name}" as {t}) as "{name}"' if t else f'        "{name}"')
    out += [f'        "{name}" as "{name}_raw"' for name in raw]
    out += [f"        {c}" for c in LINEAGE]
    return ",\n".join(out)


def person(prefix: str, name: str, dob: str, phone: str, postal: str, dob_fn: str = "kept_dob") -> list[str]:
    """New derived columns for one system's name / DOB / phone / postal."""
    return [
        f"kept_name({name}) as {prefix}_name_clean",
        f"kept_name_key({name}) as {prefix}_name_key",
        f"{dob_fn}({dob}) as {prefix}_dob_clean",
        f"kept_phone({phone}) as {prefix}_phone_e164",
        f"kept_postal({postal}) as {prefix}_postal_clean",
    ]


# table -> (id column, the person() arguments, day-first DOBs?)
ACCOUNTS = {
    "card_accounts": (
        "card_account_id",
        "cardholder",
        "cardholder_name_raw",
        "cardholder_dob_raw",
        "cardholder_phone_raw",
        "cardholder_postal_raw",
        "kept_dob_dmy",
    ),  # cards: DD-MM-YYYY
    "loan_accounts": (
        "loan_id",
        "borrower",
        "borrower_name_raw",
        "borrower_dob_raw",
        "borrower_phone_raw",
        "borrower_postal_raw",
        "kept_dob",
    ),
    "deposit_accounts": (
        "deposit_account_id",
        "holder",
        "holder_name_raw",
        "holder_dob_raw",
        "holder_phone_raw",
        "holder_postal_raw",
        "kept_dob",
    ),
}


def typed_select(table: str, columns: list[dict], exclude: tuple[str, ...] = ()) -> str:
    return f"typed as (\n    select\n{typed_columns(columns, exclude, RAW_TEXT.get(table, ()))}\n    from {{{{ source('bronze', '{table}') }}}}\n)"


def render(table: str, columns: list[dict]) -> str:
    if table == "customers":
        extras = [
            "kept_name(full_name_raw) as full_name_clean",
            "kept_name_key(first_name) as first_name_key",
            "kept_name_key(last_name) as last_name_key",
            "coalesce(date_of_birth, kept_dob(dob_raw)) as dob_clean",
            "coalesce(primary_phone_e164, kept_phone(primary_phone_raw)) as primary_phone_clean",
            "coalesce(postal_code, kept_postal(postal_code_raw)) as postal_code_clean",
            "kept_province(province_code) as province_code_clean",  # 'Ont.', 'B.C.', 'PQ' -> ON, BC, QC
        ]
        # SCD2 + CDC: the current version per key, and a current version that is deleted disappears
        return (
            f"{HEADER}with {typed_select(table, columns)},\n"
            "current_version as (\n    select * from typed\n"
            "    where effective_to_ts is null or effective_to_ts >= timestamp '9999-12-31'\n"
            "    qualify row_number() over (partition by crm_customer_id order by effective_from_ts desc) = 1\n)\n"
            f"select *,\n    {',\n    '.join(extras)}\nfrom current_version\nwhere not coalesce(is_deleted, false)\n"
        )
    if table in ACCOUNTS:
        key, prefix, name, dob, phone, postal, dob_fn = ACCOUNTS[table]
        extras = person(prefix, name, dob, phone, postal, dob_fn)
        return (
            f"{HEADER}with {typed_select(table, columns)}\n"
            f"select *,\n    {',\n    '.join(extras)}\nfrom typed\n"
            f"-- one row per account: the latest snapshot\n"
            f"qualify row_number() over (partition by {key} order by snapshot_date desc, _loaded_at desc) = 1\n"
        )
    if table == "external":
        extras = [
            "kept_name(subject_name_reported) as subject_name_clean",
            "case when risk_score is null then null else cume_dist() over "
            "(partition by risk_score_model, risk_score is null order by risk_score) end as risk_score_percentile",
        ]
        return f"{HEADER}with {typed_select(table, columns)}\nselect *,\n    {',\n    '.join(extras)}\nfrom typed\n"
    if table == "contact_history":
        # schema drift: channel was renamed channel_v2 on 26 Sep; silver keeps the dictionary name
        return (
            f"{HEADER}with {typed_select(table, columns)}\n"
            "select * exclude (channel_v2) replace (coalesce(channel_v2, channel) as channel) from typed\n"
        )
    return f"{HEADER}with {typed_select(table, columns)}\nselect * from typed\n"


def quarantine(table: str) -> str | None:
    """quarantine.<table>: one row per value a cleaning rule could not parse (kept.data.clean.QuarantineRecord)."""

    def check(
        key: str, column: str, clean: str, reason: str, frm: str | None = None, where: str | None = None
    ) -> str:
        frm = frm or f"{{{{ ref('{table}') }}}}"
        where = where or f"{column} is not null and {clean} is null"
        return (
            f"select '{table}' as \"table\", {key}::varchar as row_id, '{column}' as \"column\", "
            f"{column}::varchar as raw_value, '{reason}' as reason\nfrom {frm} where {where}"
        )

    dob = "unparseable, impossible, future or ambiguous date"
    if table == "customers":
        key = "crm_customer_id"
        checks = [
            check(key, "dob_raw", "dob_clean", dob),
            check(key, "primary_phone_raw", "primary_phone_clean", "not a valid Canadian phone number"),
            check(key, "postal_code_raw", "postal_code_clean", "not a valid Canadian postal code"),
            check(key, "province_code", "province_code_clean", "not a Canadian province or territory"),
            check(
                key,
                "is_deleted",
                "",
                "current version deleted in CRM (CDC); left out of silver",
                frm="{{ source('bronze', 'customers') }}",
                where="lower(is_deleted) = 'true' and (effective_to_ts is null or effective_to_ts >= '9999-12-31')",
            ),
        ]
    elif table in ACCOUNTS:
        key, prefix, _, dob_col, phone, postal, _ = ACCOUNTS[table]
        checks = [
            check(key, dob_col, f"{prefix}_dob_clean", dob),
            check(
                key,
                phone,
                f"{prefix}_phone_e164",
                "not a valid or complete phone number (masked or truncated)",
            ),
            check(key, postal, f"{prefix}_postal_clean", "not a valid Canadian postal code"),
        ]
    else:
        return None
    return (
        f"{HEADER}{{{{ config(schema='quarantine', alias='{table}') }}}}\n\n"
        + "\n\nunion all\n\n".join(checks)
        + "\n"
    )


def main(schema_json: str) -> None:
    schema = json.load(open(schema_json))
    n_q = 0
    for table, spec in schema.items():
        (SILVER / f"{table}.sql").write_text(render(table, spec["columns"]))
        if q := quarantine(table):
            (SILVER / f"quarantine_{table}.sql").write_text(q)
            n_q += 1
    print(f"wrote {len(schema)} silver models and {n_q} quarantine models to {SILVER}")


if __name__ == "__main__":
    main(sys.argv[1])
